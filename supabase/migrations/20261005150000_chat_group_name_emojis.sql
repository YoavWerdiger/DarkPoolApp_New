update chat_groups g set name = v.emoji || g.name, updated_at = now()
from (values
  ('שאלות תשובות','🗣️⁉️'),
  ('דיוני - פניסטוקס','🗣️🧨'),
  ('דיונים - כללי','🗣️'),
  ('ניתוחים ורעיונות שלכם','🗣️'),
  ('שאלות בלייבים','🗣️🎥'),
  ('סווינגים והשקעות','🔇🌟'),
  ('מסחר יומי','🔇🌟'),
  ('פניסטוקס (סיכון גבוה)','🌟')
) as v(base, emoji)
where g.name = v.base;
